    private const int _miscBoxSlotCount = 500;

    private const long _itemBoxMatchAddr = 0x14135349B;
    private static readonly byte[] _itemBoxMatchPattern = [0x48, 0x05, 0x08, 0x8a, 0x03, 0x00];

    public static bool IsAddrMatch()
    {
        try
        {
            return MemoryUtil
                .AsSpan<byte>(_itemBoxMatchAddr, _itemBoxMatchPattern.Length)
                .SequenceEqual(_itemBoxMatchPattern);
        }
        catch (Exception e)
        {
            Logging.Error(e.ToString());
            return false;
        }
    }

    public static bool Take(UserData userdata, ref Item item, int id, int count,out int takenCount)
    {
        takenCount = 0;
        if (id == 0 || count <= 0 || (item.Id > 0 && item.Id != id))
            return false;
        var category = GetItemCategory(id);
        if (!TryRemoveFromBox(userdata, category, id, count, out var removedCount))
            return false;
        item.Id = id;
        item.Count = removedCount;
        takenCount = removedCount;
        return true;
    }

    public static bool Restock(UserData userdata, ref Item item, int targetCount, out int restockedCount)
    {
        restockedCount = 0;
        if (item.Id == 0 || targetCount <= 0)
            return false;

        var need = targetCount - item.Count;
        if (need <= 0)
            return false;

        var category = GetItemCategory(item.Id);
        if (!TryRemoveFromBox(userdata, category, item.Id, need, out var removedCount))
            return false;

        item.Count += removedCount;
        restockedCount = removedCount;
        return true;
    }

    public static bool Store(UserData userdata, ref Item item, out int storedCount)
    {
        storedCount = 0;
        if (item.Id == 0 || item.Count <= 0)
            return false;

        var category = GetItemCategory(item.Id);

        if (!TryAddToBox(userdata, category, item.Id, item.Count, out var addedCount))
            return false;
        storedCount = addedCount;
        if (addedCount != item.Count)
        {
            item.Count -= addedCount;
            return false;
        }
        item.Id = 0;
        item.Count = 0;
        return true;
    }

    private static (nint addr, int count) GetCategoryBoxAddress(ItemCategory category) => category switch
    {
        ItemCategory.Item => (_itemBoxAddr, _itemBoxSlotCount),
        ItemCategory.Ammo => (_ammoBoxAddr, _ammoBoxSlotCount),
        ItemCategory.Material => (_materialBoxAddr, _materialBoxSlotCount),
        ItemCategory.Misc => (_miscBoxAddr, _miscBoxSlotCount),
        _ => throw new NotImplementedException(),
    };

    public static int FindSlotIndex(UserData userdata, ItemCategory category, int id)
    {
        (var addr, var slotCount) = GetCategoryBoxAddress(category);
        for (int i = 0; i < slotCount; i++)
        {
            var item = userdata.Get<Item>(addr + i * _itemSize);
            if (item.Id == id) return i;
        }
        return -1;
    }

    public static ref Item GetSlot(UserData userdata, ItemCategory category, int index)
    {
        (var addr, var slotCount) = GetCategoryBoxAddress(category);
        if (index < 0 || index >= slotCount)
            throw new ArgumentOutOfRangeException(nameof(index));
        return ref userdata.GetRef<Item>(addr + (index * _itemSize));
    }


    private static void SetSlotCount(ref Item item, int count)
    {
        if (count < 0) count = 0;
        item.Count = count;
        if (count == 0)
            item.Id = 0;
    }

    public static bool TryAddToBox(UserData userdata, ItemCategory category, int id, int count, out int addedCount)
    {
        addedCount = 0;
        if (id == 0 || count <= 0) return false;

        var slot = FindSlotIndex(userdata, category, id);
        if (slot == -1)
        {
            slot = FindSlotIndex(userdata, category, 0);
            if (slot == -1) return false;
        }

        ref var boxItem = ref GetSlot(userdata, category, slot);
        if (boxItem.Id == 0)
            boxItem.Count = 0;

        var dst = Math.Min(boxItem.Count + count, 9999);
        addedCount = dst - boxItem.Count;

        if (addedCount == 0) return false;

        if (boxItem.Id == 0)
            boxItem.Id = id;

        SetSlotCount(ref boxItem, dst);
        return true;
    }

    public static bool TryRemoveFromBox(UserData userdata, ItemCategory category, int id, int count, out int removedCount)
    {
        removedCount = 0;
        if (id == 0 || count <= 0) return false;
        var slot = FindSlotIndex(userdata, category, id);
        if (slot == -1) return false;

        ref var boxItem = ref GetSlot(userdata, category, slot);
        if (boxItem.Id == 0)
            boxItem.Count = 0;

        if (boxItem.Count < count)
        {
            removedCount = boxItem.Count;
            SetSlotCount(ref boxItem, 0);
        }
        else
        {
            removedCount = count;
            SetSlotCount(ref boxItem, boxItem.Count - count);
        }
        return removedCount != 0;
    }


